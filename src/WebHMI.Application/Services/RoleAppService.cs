using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using Abp.Application.Services;
using Abp.Application.Services.Dto;
using Abp.Authorization;
using Abp.Domain.Repositories;
using Abp.Extensions;
using Abp.IdentityFramework;
using Abp.Linq.Extensions;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using WebHMI.Dtos.Roles;
using WebHMI.Helpers;
using Abp.Auditing;
using WebHMI.Authorization.Roles;
using WebHMI.Authorization.Users;
using WebHMI.WebHMI.Dbo;
using WebHMI.Filters;

namespace WebHMI.Services
{
	/// <summary>
	/// Application service class generated by ABP framework.
	/// </summary>
	[AbpAuthorize(Permissions.Pages_Roles)]
	public class RoleAppService : AsyncCrudAppService<Role, RoleDto, int, FilteredRequestDto, CreateRoleDto, RoleDto>
	{
		private readonly RoleManager _roleManager;
		private readonly UserManager _userManager;

		public RoleAppService(IRepository<Role> repository, RoleManager roleManager, UserManager userManager)
			: base(repository)
		{
			_roleManager = roleManager;
			_userManager = userManager;
		}

		[Audited]
		public override async Task<RoleDto> CreateAsync(CreateRoleDto input)
		{
			CheckCreatePermission();

			var role = ObjectMapper.Map<Role>(input);
			role.SetNormalizedName();

			CheckErrors(await _roleManager.CreateAsync(role));

			var grantedPermissions = PermissionManager
				.GetAllPermissions()
				.Where(p => input.GrantedPermissions.Contains(p.Name))
				.ToList();

			await _roleManager.SetGrantedPermissionsAsync(role, grantedPermissions);

			return MapToEntityDto(role);
		}

		public ListResultDto<PermissionsDto> GetAllPermissions()
		{
			var permissions = PermissionManager
				.GetAllPermissions()
				.Where(p => p.Parent is null);

			var result = new List<PermissionsDto>();

			foreach (var permission in permissions)
			{
				var permissionsDto = new PermissionsDto();
				permissionsDto.GroupName = permission.Name.Replace("Pages.", string.Empty);

				// Add main one
				permissionsDto.Permissions.Add(new PermissionItem
				{
					Name = permission.Name,
					Description = permission.Description?.ToString()
				});

				// Add all childs (1 level only)
				foreach (var child in permission.Children)
				{
					permissionsDto.Permissions.Add(new PermissionItem
					{
						Name = child.Name,
						Description = child.Description?.ToString()
					});
				}

				result.Add(permissionsDto);
			}

			return new ListResultDto<PermissionsDto>(result);
		}

		public override Task<PagedResultDto<RoleDto>> GetAllAsync(FilteredRequestDto input)
		{
			return ApplicationServiceBase.ApplyFilter(
				Repository.GetAllIncluding(x => x.Permissions),
				input,
				ObjectMapper.Map<RoleDto>);
		}

		public async Task<ListResultDto<RoleListDto>> GetRolesAsync(GetRolesInput input)
		{
			var roles = await _roleManager
				.Roles
				.WhereIf(
					!input.Permission.IsNullOrWhiteSpace(),
					r => r.Permissions.Any(rp => rp.Name == input.Permission && rp.IsGranted)
				)
				.ToListAsync();

			return new ListResultDto<RoleListDto>(ObjectMapper.Map<List<RoleListDto>>(roles));
		}

		[Audited]
		public override async Task<RoleDto> UpdateAsync(RoleDto input)
		{
			CheckUpdatePermission();

			var role = await _roleManager.GetRoleByIdAsync(input.Id);

			ObjectMapper.Map(input, role);

			CheckErrors(await _roleManager.UpdateAsync(role));

			var grantedPermissions = PermissionManager
				.GetAllPermissions()
				.Where(p => input.GrantedPermissions.Contains(p.Name))
				.ToList();

			await _roleManager.SetGrantedPermissionsAsync(role, grantedPermissions);

			return MapToEntityDto(role);
		}

		[Audited]
		public override async Task DeleteAsync(EntityDto<int> input)
		{
			CheckDeletePermission();

			var role = await _roleManager.FindByIdAsync(input.Id.ToString());
			var users = await _userManager.GetUsersInRoleAsync(role.NormalizedName);

			foreach (var user in users)
			{
				CheckErrors(await _userManager.RemoveFromRoleAsync(user, role.NormalizedName));
			}

			CheckErrors(await _roleManager.DeleteAsync(role));
		}

		protected override async Task<Role> GetEntityByIdAsync(int id)
		{
			return await Repository.GetAllIncluding(x => x.Permissions).FirstOrDefaultAsync(x => x.Id == id);
		}

		protected virtual void CheckErrors(IdentityResult identityResult)
		{
			identityResult.CheckErrors(LocalizationManager);
		}

		public async Task<GetRoleForEditOutput> GetRoleForEdit(EntityDto input)
		{
			var permissions = PermissionManager.GetAllPermissions();
			var role = await _roleManager.GetRoleByIdAsync(input.Id);
			var grantedPermissions = (await _roleManager.GetGrantedPermissionsAsync(role)).ToArray();
			var roleEditDto = ObjectMapper.Map<RoleEditDto>(role);

			return new GetRoleForEditOutput
			{
				Role = roleEditDto,
				Permissions = ObjectMapper.Map<List<FlatPermissionDto>>(permissions).OrderBy(p => p.DisplayName).ToList(),
				GrantedPermissionNames = grantedPermissions.Select(p => p.Name).ToList()
			};
		}
	}
}



